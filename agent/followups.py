"""Phase 7: one approved follow-up per lead, built only from the sent initial's grounding.

A follow-up is never generated by the LLM. It is a fixed template whose evidence,
hook and example questions are copied from the initial message that was actually
sent, so every grounding check that protected the initial still applies. Drafting
requires the wait period to have elapsed and no inbound event (reply, opt-out,
bounce, auto-reply) on the thread; approval and sending are separate steps that
re-check all of this.
"""

import json
from datetime import datetime, timedelta

from agent.config import FOLLOWUP_TEMPLATE, Settings
from agent.evidence import draft_hash, validate_draft
from agent.models import Message, utc_now

FOLLOWUP_TEMPLATE_VERSION = 1
BLOCKING_INBOUND = ("reply", "opt_out", "bounce_hard", "spam_block", "auto_reply")


class FollowupError(ValueError):
    """Safe user-facing reason a follow-up cannot be drafted or sent."""


def initial_for(db, lead_id) -> Message | None:
    row = db.connection.execute(
        "SELECT id FROM messages WHERE lead_id=? AND kind='initial'", (lead_id,)
    ).fetchone()
    return db.get_message(row[0]) if row else None


def render_followup(initial: Message, postal_address: str) -> tuple[str, str]:
    if not postal_address.strip():
        raise FollowupError("Configure a physical postal address before drafting a follow-up")
    slots = (initial.personalization or {}).get("slots") or {}
    first_name = slots.get("first_name") or "there"
    subject = "Re: " + initial.subject.removeprefix("Owner-only test: ")
    body = FOLLOWUP_TEMPLATE.format(first_name=first_name, postal_address=postal_address.strip())
    if (initial.personalization or {}).get("owner_test") is True:
        subject = "Owner-only test: " + subject
        body = "This is an owner-only delivery test.\n\n" + body
    validate_draft(subject, body)
    return subject, body


def build_followup(db, initial: Message, postal_address: str) -> Message:
    subject, body = render_followup(initial, postal_address)
    envelope = {
        "followup_of": initial.id,
        "initial_content_hash": initial.content_hash,
        "postal_address": postal_address.strip(),
        "template_version": FOLLOWUP_TEMPLATE_VERSION,
        "kind": "followup",
    }
    if (initial.personalization or {}).get("owner_test") is True:
        envelope["owner_test"] = True
    return Message(
        lead_id=initial.lead_id,
        kind="followup",
        subject=subject,
        body=body,
        evidence=initial.evidence,
        hook_line=initial.hook_line,
        hook_evidence=initial.hook_evidence,
        hook_source_url=initial.hook_source_url,
        example_questions=initial.example_questions,
        confidence=initial.confidence,
        requires_manual_review=True,
        personalization=envelope,
    )


def validate_followup(db, message: Message) -> None:
    """Stored follow-ups must equal a fresh rebuild from the sent initial."""
    envelope = message.personalization or {}
    initial = initial_for(db, message.lead_id)
    if (
        initial is None
        or envelope.get("kind") != "followup"
        or envelope.get("template_version") != FOLLOWUP_TEMPLATE_VERSION
        or envelope.get("followup_of") != initial.id
        or envelope.get("initial_content_hash") != initial.content_hash
    ):
        raise FollowupError("Follow-up is not linked to the current initial message")
    rebuilt = build_followup(db, initial, envelope.get("postal_address", ""))
    for key in (
        "subject",
        "body",
        "evidence",
        "hook_line",
        "hook_evidence",
        "hook_source_url",
        "example_questions",
        "personalization",
    ):
        if getattr(rebuilt, key) != getattr(message, key):
            raise FollowupError("Follow-up content must be rebuilt from the template")
    if message.id is not None:
        expected = draft_hash(
            message.subject,
            message.body,
            json.dumps([e.model_dump() for e in message.evidence]),
            json.dumps(envelope),
        )
        if message.content_hash != expected:
            raise FollowupError("Follow-up content hash mismatch")


def followup_blockers(db, lead_id, settings: Settings, now: datetime | None = None) -> list[str]:
    """Fresh eligibility; used for drafting, approval preview and the send preflight."""
    now = now or utc_now()
    lead = db.get_lead(lead_id)
    initial = initial_for(db, lead_id)
    blockers = []
    if initial is None or initial.status != "sent" or not initial.sent_at:
        blockers.append("initial_not_sent")
    elif now - initial.sent_at < timedelta(days=settings.followup_wait_days):
        blockers.append("followup_wait_not_elapsed")
    if initial is not None and not initial.gmail_thread_id:
        blockers.append("initial_thread_unknown")
    if lead.stage != "contacted":
        blockers.append("lead_not_awaiting_reply")
    if lead.email_status == "bounced":
        blockers.append("email_bounced")
    if db.is_suppressed(lead.email, lead.domain):
        blockers.append("suppressed")
    placeholders = ",".join("?" * len(BLOCKING_INBOUND))
    inbound = db.connection.execute(
        f"SELECT 1 FROM inbound_events WHERE lead_id=? AND kind IN ({placeholders}) LIMIT 1",
        (lead_id, *BLOCKING_INBOUND),
    ).fetchone()
    if inbound:
        blockers.append("inbound_activity_on_thread")
    synced = db.connection.execute(
        "SELECT 1 FROM gmail_sync_runs WHERE outcome='ok' AND finished_at>=? LIMIT 1",
        ((now - timedelta(hours=24)).isoformat(),),
    ).fetchone()
    if not synced:
        # Never follow up without having checked for a reply recently.
        blockers.append("gmail_sync_required")
    return blockers


def due_followups(db, settings: Settings, now: datetime | None = None) -> list[dict]:
    now = now or utc_now()
    rows = db.connection.execute(
        "SELECT l.id FROM leads l JOIN messages m ON m.lead_id=l.id AND m.kind='initial' "
        "WHERE m.status='sent' AND l.stage='contacted' AND NOT EXISTS "
        "(SELECT 1 FROM messages f WHERE f.lead_id=l.id AND f.kind='followup') ORDER BY m.sent_at"
    ).fetchall()
    result = []
    for (lead_id,) in rows:
        blockers = followup_blockers(db, lead_id, settings, now)
        result.append({"lead_id": lead_id, "due": not blockers, "blockers": blockers})
    return result


def draft_followup(db, lead_id, settings: Settings, now: datetime | None = None) -> Message:
    blockers = followup_blockers(db, lead_id, settings, now)
    if blockers:
        raise FollowupError(", ".join(blockers))
    initial = initial_for(db, lead_id)
    return db.create_draft(build_followup(db, initial, settings.postal_address))
